export function surr158Pct(y: number, age: number): number {
  const A = SURR158_AGES;
  const a = Math.max(A[0], Math.min(A[A.length - 1], age));
  if (a <= A[0]) return SURR158_BY_AGE[A[0]][y - 1] / 100;
  for (let i = 1; i < A.length; i++) {
    if (a <= A[i]) {
      const lo = A[i - 1], hi = A[i];
      const vlo = SURR158_BY_AGE[lo][y - 1], vhi = SURR158_BY_AGE[hi][y - 1];
      return (vlo + (vhi - vlo) * (a - lo) / (hi - lo)) / 100;
    }
  }
  return SURR158_BY_AGE[A[A.length - 1]][y - 1] / 100;
}